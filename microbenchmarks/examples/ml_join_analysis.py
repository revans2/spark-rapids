def analyze_thresholds(df, features):
    """Analyze simple threshold-based rules."""
    print("Analyzing threshold-based heuristics...")
    print()
    
    # Hash vs Sort based on cardinality
    print("1. HASH vs SORT Strategy Selection:")
    print()
    
    for threshold in [0.05, 0.10, 0.15, 0.20, 0.25]:
        low_card = df[features['MinCardinality'] < threshold]
        if len(low_card) == 0:
            continue
        
        hash_count = low_card[low_card['BestStrategy'].str.contains('hash')].shape[0]
        sort_count = low_card[low_card['BestStrategy'] == 'sort'].shape[0]
        total = hash_count + sort_count
        
        if total > 0:
            sort_pct = (sort_count / total) * 100
            print(f"  Cardinality < {threshold*100:>5.1f}%: {sort_pct:>5.1f}% prefer SORT "
                  f"({sort_count}/{total} configs)")
    
    print()
    print("  RECOMMENDATION:")
    
    # Find the threshold where sort becomes dominant (>60%)
    best_threshold = None
    for threshold in np.arange(0.01, 0.30, 0.01):
        low_card = df[features['MinCardinality'] < threshold]
        if len(low_card) < 5:
            continue
        hash_count = low_card[low_card['BestStrategy'].str.contains('hash')].shape[0]
        sort_count = low_card[low_card['BestStrategy'] == 'sort'].shape[0]
        total = hash_count + sort_count
        if total > 0 and (sort_count / total) > 0.6:
            best_threshold = threshold
            break
    
    if best_threshold:
        print(f"    Use SORT when cardinality < {best_threshold*100:.1f}%")
        print(f"    Use HASH otherwise")
    else:
        print("    Use HASH as default (SORT not clearly beneficial)")
    print()
    
    # Hash Object vs Direct
    print("2. HASH OBJECT vs DIRECT:")
    print()
    
    hash_object = df[df['BestStrategy'] == 'hash_object']
    hash_direct = df[df['BestStrategy'] == 'hash_direct']
