def create_build_probe_features(df, verbose=True):
    """
    Create feature matrix using build/probe terminology instead of left/right.
    
    ONLY includes features available in production:
    - Build side: rows, distinct keys, cardinality, key type, avg key bytes
    - Probe side: rows, avg key bytes
    - Key characteristics: type, number of columns
    
    Excludes features NOT available in production:
    - *MemoryMB (all memory features)
    - ProbeDistinctKeys, ProbeCardinalityPct
    - Distribution skew (BuildDistSkew, ProbeDistSkew, MaxDistSkew)
    
    Build side = smaller side used to construct hash table (or side that determines sort order)
    Probe side = larger side that probes the hash table (or gets merged with sorted build)
    
    Args:
        df: DataFrame with benchmark results
        verbose: If True, print progress messages. Default True.
    """
    if verbose:
        print("Creating build/probe feature matrix (production features only)...")
    
    features = pd.DataFrame()
    
    # Determine build and probe sides (smaller side is typically build side)
    is_left_build = df['LeftRows'] <= df['RightRows']
    
    # Build side features (from smaller table)
    features['BuildRows'] = df.apply(
        lambda row: row['LeftRows'] if row['LeftRows'] <= row['RightRows'] else row['RightRows'],
        axis=1
    )
    features['BuildDistinctKeys'] = df.apply(
        lambda row: row['LeftDistinctKeys'] if row['LeftRows'] <= row['RightRows'] else row['RightDistinctKeys'],
        axis=1
    )
    features['BuildCardinalityPct'] = df.apply(
        lambda row: row['LeftCardinalityPct'] if row['LeftRows'] <= row['RightRows'] else row['RightCardinalityPct'],
        axis=1
    )
    features['BuildAvgKeyBytes'] = df.apply(
        lambda row: row['LeftAvgKeyBytes'] if row['LeftRows'] <= row['RightRows'] else row['RightAvgKeyBytes'],
        axis=1
    )
    
    # Probe side features (from larger table)
    # NOTE: Removed ProbeCardinalityPct and ProbeDistinctKeys - typically not calculated in production
    # Only ProbeRows is kept for size comparison
    features['ProbeRows'] = df.apply(
        lambda row: row['RightRows'] if row['LeftRows'] <= row['RightRows'] else row['LeftRows'],
        axis=1
    )
    features['ProbeAvgKeyBytes'] = df.apply(
        lambda row: row['RightAvgKeyBytes'] if row['LeftRows'] <= row['RightRows'] else row['LeftAvgKeyBytes'],
        axis=1
    )
    
    # Key columns (same for both sides)
    if 'NumKeyColumns' in df.columns:
        features['NumKeyColumns'] = df['NumKeyColumns']
    
    # Key overlap
    if 'KeyOverlapPct' in df.columns:
        features['KeyOverlapPct'] = df['KeyOverlapPct']
    
    # Derived features
    features['TotalRows'] = features['BuildRows'] + features['ProbeRows']
    features['BuildProbeRatio'] = features['BuildRows'] / features['ProbeRows']
    
    # NOTE: Focus on BuildCardinalityPct only (most important for hash table construction)
    # Removed features (not calculated/available in production):
    #   - AvgCardinality, MinCardinality, MaxCardinality (probe cardinality not needed)
    #   - ProbeCardinalityPct (minimal impact on performance)
    #   - ProbeDistinctKeys (not calculated in production)
    #   - DistinctRatio (depends on ProbeDistinctKeys)
    #   - BuildDistSkew, ProbeDistSkew, MaxDistSkew (distribution skew not calculated)
    
    # Key characteristics (use left side since keys must match on both sides)
    if 'LeftKeyType' in df.columns and 'NumKeyColumns' in df.columns:
        features['KeyCharacteristics'] = df.apply(
            lambda row: classify_key_characteristics(row['LeftKeyType'], row['NumKeyColumns']),
            axis=1
        )
    
    # Key type complexity score
    key_type_scores = {
        'int': 1, 'long': 2, 
        'decimal(9,2)': 1, 'decimal(18,2)': 2, 'decimal(38,2)': 3,
        'string_short': 4, 'string_medium': 5, 'string_long': 6
    }
    
    # Build and probe key type scores
    features['BuildKeyTypeScore'] = df.apply(
        lambda row: key_type_scores.get(
            row['LeftKeyType'] if row['LeftRows'] <= row['RightRows'] else row['RightKeyType'], 1
        ),
        axis=1
    )
    features['ProbeKeyTypeScore'] = df.apply(
        lambda row: key_type_scores.get(
            row['RightKeyType'] if row['LeftRows'] <= row['RightRows'] else row['LeftKeyType'], 1
        ),
        axis=1
    )
    features['MaxKeyTypeScore'] = features[['BuildKeyTypeScore', 'ProbeKeyTypeScore']].max(axis=1)
    
    # Encode KeyCharacteristics as numeric
    key_char_scores = {
        'fixed_width_32bit': 1,
        'fixed_width_64bit': 2,
        'fixed_width_128bit': 3,
        'variable_width': 4,
        'composite_all_fixed_width': 5,
        'composite_with_variable_width': 6
    }
    if 'KeyCharacteristics' in features.columns:
        features['KeyCharacteristicsScore'] = features['KeyCharacteristics'].map(key_char_scores).fillna(1)
    
    # NOTE: Distribution skew (BuildDistSkew, ProbeDistSkew, MaxDistSkew) REMOVED
    # These are not calculated in production systems
    
    # Boolean features
    if 'LeftIsPrimaryKey' in df.columns and 'RightIsPrimaryKey' in df.columns:
        features['HasPrimaryKey'] = (df['LeftIsPrimaryKey'] | df['RightIsPrimaryKey']).astype(int)
    
    # Cardinality flags based on BUILD SIDE only (most important for hash table)
    features['BuildHighCardinality'] = (features['BuildCardinalityPct'] > 0.5).astype(int)
    features['BuildLowCardinality'] = (features['BuildCardinalityPct'] < 0.1).astype(int)
    features['BuildVeryLowCardinality'] = (features['BuildCardinalityPct'] < 0.05).astype(int)
    
    # Handle any NaN or inf values
    features = features.replace([np.inf, -np.inf], np.nan)
    features = features.fillna(0)
    
    # Remove string columns that can't be used directly in ML models
    if 'KeyCharacteristics' in features.columns:
        features = features.drop('KeyCharacteristics', axis=1)
    
    if verbose:
        print(f"Created {len(features.columns)} build/probe features")
        print()
    
    return features

def classify_key_characteristics(key_type, num_key_columns):
    """
    Classify key based on width and composition characteristics.
    
    Returns one of:
    - composite_all_fixed_width: Multiple columns, all fixed-width types
    - composite_with_variable_width: Multiple columns, at least one variable-width type
    - variable_width: Single column, variable-width (strings) - BENEFITS from remapping in sort joins!
    - fixed_width_32bit: Single column, 32-bit (int, decimal(9,2))
    - fixed_width_64bit: Single column, 64-bit (long, decimal(18,2))
    - fixed_width_128bit: Single column, 128-bit (decimal(38,2))
    
    Note: Single-column variable-width (strings) CAN benefit from remapping because
    it converts expensive string comparisons to fast integer comparisons during sort.
    """
    # Determine if key type is variable width
    is_variable_width = 'string' in key_type.lower()
    
    if num_key_columns == 1:
        # Single column
        if is_variable_width:
            return 'variable_width'
        elif key_type in ['int', 'decimal(9,2)']:
            return 'fixed_width_32bit'
        elif key_type in ['long', 'decimal(18,2)']:
            return 'fixed_width_64bit'
        elif key_type in ['decimal(38,2)']:
            return 'fixed_width_128bit'
        else:
            return 'fixed_width_64bit'  # Default
    else:
        # Composite (multiple columns)
        if is_variable_width:
            return 'composite_with_variable_width'
        else:
            return 'composite_all_fixed_width'

def create_features(df):
    """Create feature matrix for ML models."""
    print("Creating feature matrix...")
    
    features = pd.DataFrame()
    
    # Numeric features (already present)
    numeric_cols = [
        'LeftRows', 'LeftDistinctKeys', 'LeftCardinalityPct', 'LeftAvgKeyBytes', 'LeftMemoryMB',
        'RightRows', 'RightDistinctKeys', 'RightCardinalityPct', 'RightAvgKeyBytes', 'RightMemoryMB',
        'NumKeyColumns', 'KeyOverlapPct'
    ]
    
    for col in numeric_cols:
        if col in df.columns:
            features[col] = df[col]
    
    # Derived features
    features['TotalRows'] = features['LeftRows'] + features['RightRows']
    features['RowRatio'] = features['LeftRows'] / features['RightRows']
    features['DistinctRatio'] = features['LeftDistinctKeys'] / features['RightDistinctKeys']
    features['AvgCardinality'] = (features['LeftCardinalityPct'] + features['RightCardinalityPct']) / 2
    features['MinCardinality'] = features[['LeftCardinalityPct', 'RightCardinalityPct']].min(axis=1)
    features['MaxCardinality'] = features[['LeftCardinalityPct', 'RightCardinalityPct']].max(axis=1)
    features['TotalMemoryMB'] = features['LeftMemoryMB'] + features['RightMemoryMB']
    features['SmallerSideRows'] = features[['LeftRows', 'RightRows']].min(axis=1)
    features['LargerSideRows'] = features[['LeftRows', 'RightRows']].max(axis=1)
    
    # NEW: Key characteristics classification
    if 'LeftKeyType' in df.columns and 'NumKeyColumns' in df.columns:
        features['KeyCharacteristics'] = df.apply(
            lambda row: classify_key_characteristics(row['LeftKeyType'], row['NumKeyColumns']),
            axis=1
        )
    
    # Categorical features - encode as numeric
    # Key type complexity score (higher = more complex)
    key_type_scores = {
        'int': 1, 'long': 2, 
        'decimal(9,2)': 1, 'decimal(18,2)': 2, 'decimal(38,2)': 3,
        'string_short': 4, 'string_medium': 5, 'string_long': 6
    }
    features['LeftKeyTypeScore'] = df['LeftKeyType'].map(key_type_scores).fillna(1)
    features['RightKeyTypeScore'] = df['RightKeyType'].map(key_type_scores).fillna(1)
    features['MaxKeyTypeScore'] = features[['LeftKeyTypeScore', 'RightKeyTypeScore']].max(axis=1)
    
    # Encode KeyCharacteristics as numeric for ML
    key_char_scores = {
        'fixed_width_32bit': 1,
        'fixed_width_64bit': 2,
        'fixed_width_128bit': 3,
        'variable_width': 4,
        'composite_all_fixed_width': 5,
        'composite_with_variable_width': 6
    }
    if 'KeyCharacteristics' in features.columns:
        features['KeyCharacteristicsScore'] = features['KeyCharacteristics'].map(key_char_scores).fillna(1)
    
    # Distribution skew score
    dist_scores = {
        'uniform': 0, 'zipf_light': 1, 'zipf_moderate': 2, 'zipf_heavy': 3
    }
    features['LeftDistSkew'] = df['LeftDistribution'].map(dist_scores).fillna(0)
    features['RightDistSkew'] = df['RightDistribution'].map(dist_scores).fillna(0)
    features['MaxDistSkew'] = features[['LeftDistSkew', 'RightDistSkew']].max(axis=1)
    
    # Boolean features
    features['HasPrimaryKey'] = (df['LeftIsPrimaryKey'] | df['RightIsPrimaryKey']).astype(int)
    features['BothHighCardinality'] = ((df['LeftCardinalityPct'] > 0.5) & (df['RightCardinalityPct'] > 0.5)).astype(int)
    features['BothLowCardinality'] = ((df['LeftCardinalityPct'] < 0.1) & (df['RightCardinalityPct'] < 0.1)).astype(int)
    
    # Handle any NaN or inf values
    features = features.replace([np.inf, -np.inf], np.nan)
    features = features.fillna(0)
    
    # Remove string columns that can't be used directly in ML models
    # (We've already encoded KeyCharacteristics as KeyCharacteristicsScore)
    if 'KeyCharacteristics' in features.columns:
        features = features.drop('KeyCharacteristics', axis=1)
    
    print(f"Created {len(features.columns)} features")
    print()
    
    return features

def find_best_strategy_per_config(df):
    """For each test configuration, find the best-performing strategy."""
    print("Identifying best strategy for each configuration...")
    
    # Group by test configuration (everything except strategy/optimization settings)
    config_cols = ['LeftRows', 'LeftDistinctKeys', 'LeftKeyType', 
                   'RightRows', 'RightDistinctKeys', 'RightKeyType',
                   'NumKeyColumns']
    
    best_strategies = []
    
    for config, group in df.groupby(config_cols, dropna=False):
        # Find the run with minimum median time
        best_idx = group['MedianTimeMs'].idxmin()
        best_row = group.loc[best_idx].copy()
        best_row['BestStrategy'] = best_row['JoinStrategy']
        best_strategies.append(best_row)
    
    result_df = pd.DataFrame(best_strategies)
    print(f"Found best strategies for {len(result_df)} unique configurations")
    print()
    
    return result_df

