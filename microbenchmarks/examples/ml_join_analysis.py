def simplify_tree_for_binary_classifier(tree_text):
    """
    Simplify decision tree by collapsing branches where all children lead to same class.
    Adapted for binary classifier (hash_direct vs sort).
    """
    lines = tree_text.split('\n')
    simplified_lines = []
    
    def get_tree_depth(line):
        """Calculate tree depth by finding position of '---' or counting '|' characters."""
        if '---' not in line:
            return -1
        # Count position of '---' as depth indicator
        return line.find('---')
    
    i = 0
    while i < len(lines):
        line = lines[i]
        
        # Check if this is a split node (has '---' but no 'class:')
        if '---' in line and 'class:' not in line:
            # Get the tree depth
            depth = get_tree_depth(line)
            
            # Look ahead to see if all children have the same class
            child_classes = set()
            j = i + 1
            
            # Collect all descendant leaf classes (not just immediate children)
            while j < len(lines):
                child_line = lines[j]
                if not child_line.strip():
                    j += 1
                    continue
                
                if '---' not in child_line:
                    j += 1
                    continue
                    
                child_depth = get_tree_depth(child_line)
                
                # If we've gone back to same or lower depth, we're done with this subtree
                if child_depth <= depth:
                    break
                
                # Collect all leaf classes in this subtree
                if 'class:' in child_line:
                    # Extract class name (before any parentheses or extra text)
                    if 'hash_direct' in child_line:
                        child_classes.add('hash_direct')
                    elif 'sort' in child_line:
                        child_classes.add('sort')
                
                j += 1
            
            # If all children have same class, simplify
            if len(child_classes) == 1:
                the_class = list(child_classes)[0]
                class_text = "hash_direct (no post-processing)" if the_class == 'hash_direct' else "sort (with/without post-processing)"
                
                # Add the original line first
                simplified_lines.append(line.rstrip())
                
                # Add the summary on a new line with proper indentation
                # Match the indentation of the split node's children (depth + 4)
                indent_str = ' ' * (depth + 4)
                simplified_lines.append(f"{indent_str}→ [All branches lead to: {class_text}]")
                
                # Skip all the children - but be careful with the index
                # We want to continue from j (which is at same or lower depth)
                i = j
                continue
        
        simplified_lines.append(line)
        i += 1
    
    return '\n'.join(simplified_lines)

def simplify_tree_text(tree_text):
    """
    Simplify decision tree text by collapsing branches where all children lead to same class.
    
    For example, if we have:
    |--- feature <= 0.5
    |   |--- class: 0
    |--- feature > 0.5
    |   |--- class: 0
    
    This simplifies to:
    |--- [All branches] → class: 0
    """
    lines = tree_text.split('\n')
    simplified_lines = []
    
    i = 0
    while i < len(lines):
        line = lines[i]
        
        # Check if this is a split node (has '---' but no 'class:')
        if '---' in line and 'class:' not in line:
            # Get the indentation level
            indent = len(line) - len(line.lstrip())
            
            # Look ahead to see if all children have the same class
            child_classes = set()
            j = i + 1
            max_child_indent = indent + 4
            
            # Collect all immediate child classes
            while j < len(lines):
                child_line = lines[j]
                if not child_line.strip():
                    j += 1
                    continue
                    
                child_indent = len(child_line) - len(child_line.lstrip())
                
                # If we've gone back to same or lower indent, we're done with children
                if child_indent <= indent:
                    break
                
                # Only look at immediate children (one level deeper)
                if child_indent == max_child_indent and 'class:' in child_line:
                    # Extract class number
                    if 'class: 0' in child_line:
                        child_classes.add(0)
                    elif 'class: 1' in child_line:
                        child_classes.add(1)
                
                j += 1
            
            # If all children have same class, simplify
            if len(child_classes) == 1:
                the_class = list(child_classes)[0]
                class_text = "DISABLE remapping" if the_class == 0 else "ENABLE remapping"
                simplified_lines.append(line.rstrip() + f"  → [All branches lead to: {class_text}]")
                # Skip all the children
                i = j
                continue
        
        simplified_lines.append(line)
        i += 1
    
    return '\n'.join(simplified_lines)

def analyze_key_remapping(df):
    """
    Analyze key remapping effectiveness with 3D breakdown:
    Join Strategy × Key Type × Number of Key Columns
    
    Provides:
    1. Separate matrices for each join strategy
    2. Strategy-specific decision trees for remapping decisions
    3. Key characteristics-based recommendations
    """
    print("="*80)
    print("KEY REMAPPING ANALYSIS")
    print("="*80)
    print()
    
    with_remap = df[df['UseKeyRemapping'] == True]
    without_remap = df[df['UseKeyRemapping'] == False]
    
    if len(with_remap) == 0 or len(without_remap) == 0:
        print("Insufficient data for key remapping analysis")
        print()
        return
    
    # Add key characteristics to dataframe
    df_with_char = df.copy()
    df_with_char['KeyCharacteristics'] = df_with_char.apply(
        lambda row: classify_key_characteristics(row['LeftKeyType'], row['NumKeyColumns']),
        axis=1
    )
    
    # Overall impact
    avg_with = with_remap['MedianTimeMs'].mean()
    avg_without = without_remap['MedianTimeMs'].mean()
    benefit = ((avg_without - avg_with) / avg_without) * 100
    
    print(f"OVERALL IMPACT:")
    print(f"  Average time with remapping:    {avg_with:.2f} ms")
    print(f"  Average time without remapping: {avg_without:.2f} ms")
    print(f"  Overall benefit:                {benefit:+.1f}%")
    print()
    
    # ========================================================================
    # SECTION 1: Strategy-Specific Matrices (NumKeyColumns × KeyType)
    # ========================================================================
    
    strategies_to_analyze = ['sort', 'hash_object', 'hash_direct']
    
    for strategy in strategies_to_analyze:
        print("="*80)
        print(f"REMAPPING BENEFIT MATRIX: {strategy.upper()}")
        print("="*80)
        print("Matrix: NumKeyColumns (horizontal) × KeyType (vertical)")
        print()
        
        strat_df = df_with_char[df_with_char['JoinStrategy'] == strategy]
        
        if len(strat_df) == 0:
            print(f"  No data available for {strategy}")
            print()
            continue
        
        # Get unique values
        num_cols_list = sorted(strat_df['NumKeyColumns'].unique())
        key_types = sorted(strat_df['LeftKeyType'].unique())
        
        # Print header
        print(f"{'Key Type':<20s}", end='')
        for num_cols in num_cols_list:
            print(f" {num_cols:>2d} col(s)", end='')
        print("   Overall")
        print("-" * (20 + 9 * len(num_cols_list) + 12))
        
        # Print matrix
        for key_type in key_types:
            print(f"{key_type:<20s}", end='')
            
            # Each num_cols
            for num_cols in num_cols_list:
                subset = strat_df[(strat_df['LeftKeyType'] == key_type) & 
                                   (strat_df['NumKeyColumns'] == num_cols)]
                with_r = subset[subset['UseKeyRemapping'] == True]['MedianTimeMs'].mean()
                without_r = subset[subset['UseKeyRemapping'] == False]['MedianTimeMs'].mean()
                
                if not pd.isna(with_r) and not pd.isna(without_r) and without_r > 0:
                    benefit_pct = ((without_r - with_r) / without_r) * 100
                    
                    # Mark based on expectations
                    # For SORT joins: variable-width benefits even with single column!
                    # For HASH joins: only composite keys benefit
                    is_variable_width = 'string' in key_type.lower()
                    
                    if num_cols == 1:
                        if strategy == 'sort' and is_variable_width:
                            # Sort + variable width: expect benefit even for single column
                            marker = "✓" if benefit_pct > 5 else ("~" if benefit_pct >= -5 else "✗")
                        else:
                            # Hash or fixed-width: no benefit expected for single column
                            marker = "⚠" if benefit_pct > 5 else ("~" if benefit_pct >= -5 else "✓")
                    else:
                        # Composite keys: generally expect benefit
                        marker = "✓" if benefit_pct > 5 else ("~" if benefit_pct >= -5 else "✗")
                    
